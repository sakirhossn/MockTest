const LOCAL_STORAGE_CUSTOM_PYQ_KEY = 'mocktest_custom_pyq_papers';

/**
 * Retrieves all PYQ papers (official seed papers + any papers fetched via AI or added locally)
 */
export function getAllPYQPapers(): PYQPaper[] {
  try {
    const raw = localStorage.getItem(LOCAL_STORAGE_CUSTOM_PYQ_KEY);
    if (!raw) return OFFICIAL_PYQ_PAPERS;
    const custom: PYQPaper[] = JSON.parse(raw);
    if (!Array.isArray(custom)) return OFFICIAL_PYQ_PAPERS;

    // Merge: custom papers first, then official papers avoiding duplicate IDs
    const officialFiltered = OFFICIAL_PYQ_PAPERS.filter(
      (off) => !custom.some((c) => c.id === off.id)
    );
    return [...custom, ...officialFiltered];
  } catch (e) {
    return OFFICIAL_PYQ_PAPERS;
  }
}

/**
 * Saves a newly generated or imported PYQ paper to local storage
 */
export function saveCustomPYQPaper(paper: PYQPaper): void {
  try {
    const current = getAllPYQPapers();
    const updated = [paper, ...current.filter((p) => p.id !== paper.id)];
    localStorage.setItem(LOCAL_STORAGE_CUSTOM_PYQ_KEY, JSON.stringify(updated));
  } catch (e) {
    console.warn('Failed to save custom PYQ paper to localStorage', e);
  }
}

/**
 * Converts a PYQPaper directly into a playable MockTest for the ExamPortal
 */
export function convertPYQToMockTest(paper: PYQPaper): MockTest {
  return {
    id: paper.id,
    title: paper.title,
    examType: paper.examSlug as any,
    description: `${paper.description} [${paper.year} • ${paper.shift} • ${paper.sourceReference}]`,
    durationMinutes: paper.durationMinutes,
    totalMarks: paper.questions.length * paper.marksPerQuestion,
    marksPerQuestion: paper.marksPerQuestion,
    negativeMark: paper.negativeMark,
    sections: paper.sections,
    questions: paper.questions,
    createdAt: new Date().toISOString(),
    isAiGenerated: false,
    sourceDocName: `${paper.examName} ${paper.year} ${paper.shift}`,
  };
}
